def build_long_table() -> pd.DataFrame:
    """Build a (lag, i, sample_size, algorithm) -> [TPR, FDR, SHD] DataFrame."""
    df = pd.DataFrame.from_dict(DATA, orient="index", columns=METRICS)
    df.index = pd.MultiIndex.from_tuples(df.index, names=INDEX_NAMES)
    return df.sort_index()


def _format_mean_std(values: pd.Series) -> str:
    return f"{values.mean():.2f} ± {values.std():.2f}"


def summary_by(level: str, levels_to_iterate, table: pd.DataFrame) -> pd.DataFrame:
    """Summarise mean ± std per (algorithm, level=value) for each metric."""
    rows = []
    for algorithm in ALGORITHMS:
        name = f"{algorithm} (Ours)" if algorithm == "DCD" else algorithm
        row = [name]
        for value in levels_to_iterate:
            mask = (table.index.get_level_values("algorithm") == algorithm) & (
                table.index.get_level_values(level) == value
            )
            subset = table[mask]
            for metric in METRICS:
                row.append(_format_mean_std(subset[metric]))
        rows.append(row)

    columns = [("Method", "")] + [
        (str(value), metric) for value in levels_to_iterate for metric in METRICS
    ]
    df = pd.DataFrame(rows)
    df.columns = pd.MultiIndex.from_tuples(columns)
    return df


def main() -> None:
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)

    t1 = build_long_table()
    t1.to_csv(RESULTS_DIR / "algorithm_comparison.csv")
    print(f"Wrote {RESULTS_DIR / 'algorithm_comparison.csv'}")

    by_n = summary_by("sample_size", SAMPLE_SIZES, t1)
    by_n_path = RESULTS_DIR / "statistics_by_sample_size.csv"
    by_n.to_csv(by_n_path)
    print(f"Wrote {by_n_path}")

    by_i = summary_by("i", I_VALUES, t1)
    by_i_path = RESULTS_DIR / "statistics_by_i_value.csv"
    by_i.to_csv(by_i_path)
    print(f"Wrote {by_i_path}")

    print("\nSummary by sample size:")
    print(by_n.to_string(index=False))
    print("\nSummary by number of variables (i):")
    print(by_i.to_string(index=False))


if __name__ == "__main__":
    main()
